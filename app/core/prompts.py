def get(name: str) -> str:
    """按名取提示词原文。"""
    if name not in PROMPTS:
        raise AppError(f"未注册的提示词：{name}")
    return PROMPTS[name]


def render(name: str, **variables: Any) -> str:
    """取提示词并按变量渲染；变量缺失时抛错而非静默留空。

    用 str.format 渲染，{ 和 } 需转义为 {{ }}（dream prompt 里的 JSON 样例已处理）。
    """
    template = get(name)
    try:
        return template.format(**variables)
    except KeyError as exc:
        raise AppError(f"提示词「{name}」缺少变量：{exc.args[0]}") from exc

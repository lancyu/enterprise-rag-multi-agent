"""中文文本处理的**唯一实现处**。

为什么单独成模块
----------------
「哪些字算中文」「哪些字是虚词」这两件事，此前在 ``app/rag/lexical.py`` 与
``app/rag/retriever.py`` 里**各写了一遍**：虚词集合内容逐字相同，``_cjk_runs``
函数体一字不差，连「汉字区间」都有 ``一-鿿`` 与 ``\\u4e00-\\u9fff`` 两种写法。
``lexical.py`` 的注释甚至写着「与 retriever._CJK_STOP 一致」——用注释记录了重复，
而不是消除它。

抄两遍的代价不是多打几个字，而是**改一处忘一处**：虚词表加一个字，只有倒排索引
受益，向量侧的字符集不受影响，两路召回于是悄悄分叉，且不会有任何报错。

为什么放在 ``app/utils/``
----------------------------
`rag` 与 `providers` 都需要它。``utils`` 是最内层，两边都能依赖而不产生反向依赖；
放进 ``rag`` 则 ``providers → rag`` 会变成反向依赖，放进 ``providers`` 同理。
"""
import re
from typing import List

# 汉字区间（CJK 统一表意文字 · 基本区）。**只在这里写一次**：
# 同一区间用两种写法表达，读代码的人会以为它们不是一回事。
#: 区间本身（供需要自建正则的调用方拼接，如 ``app/providers/embeddings.py``）。
CJK_RANGE = "\u4e00-\u9fff"

#: 匹配单个汉字的正则。
CJK_CHAR = re.compile(f"[{CJK_RANGE}]")

#: 连续中文串的切分模式（用于 ``re.split`` 等场景）。
CJK_RUN_SPLIT = re.compile(f"[^{CJK_RANGE}]+")

#: 中文高频虚词 —— **不计入**词面匹配，也**不计入**倒排索引。
#:
#: 这是区分度的关键。若不剔除，「年假有多少天」里的「有/多/少」会命中任何含
#: 「有多少人」的片段，「的/了/是」更是几乎出现在每个汉语句子里，会让所有片段的
#: 词面分一起冲到 1.0，词面路彻底失去排序能力。
CJK_STOP = frozenset(
    "的了是有着和在就都而我你他她它们这那吗呢吧啊很太最更也很还再又只才不没无"
    "给让向往把被对从到以为及其或与个们多少怎如何什么可以请问谢谢"
)


def cjk_runs(text: str) -> List[str]:
    """切出长度 ≥2 的连续中文串。

    如「年假有多少天」→ ``['年假', '有多少天']``。

    只保留 ≥2 字的串：单字串（如「问」）在中文里几乎没有区分度，
    留着只会让所有片段共享同一批 token。
    """
    return [run for run in CJK_RUN_SPLIT.split(text) if len(run) >= 2]
